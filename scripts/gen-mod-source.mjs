#!/usr/bin/env node
// Embeds packages/mod/plugin/** into packages/core/src/mod-source.generated.ts.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pluginDir = join(root, "packages/mod/plugin");
const outFile = join(root, "packages/core/src/mod-source.generated.ts");

const files = {};
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else files[relative(pluginDir, full).split("\\").join("/")] = readFileSync(full, "utf8");
  }
}
walk(pluginDir);
const entries = Object.entries(files)
  .map(([k, v]) => "  " + JSON.stringify(k) + ": " + JSON.stringify(v) + ",")
  .join("\n");
const content = "// Generated by scripts/gen-mod-source.mjs — do not edit.\n" +
  "export const MOD_PLUGIN_VERSION = " + JSON.stringify(files[".claude-plugin/plugin.json"]?.match(/"version"\s*:\s*"([^"]+)"/)?.[1] ?? "0.0.0") + ";\n" +
  "export const MOD_PLUGIN_FILES: Record<string, string> = {\n" + entries + "\n};\n";
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, content);
console.log("wrote", outFile, Object.keys(files).length, "files");
